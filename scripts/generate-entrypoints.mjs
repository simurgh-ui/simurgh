import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format } from 'prettier';

const root = resolve(import.meta.dirname, '..');
const prettierOptions = { singleQuote: true, trailingComma: 'all', semi: true };
const registry = JSON.parse(
  await readFile(resolve(root, 'packages/registry/registry.json'), 'utf8'),
);

for (const framework of ['react', 'vue', 'angular']) {
  const extension = framework === 'react' ? 'tsx' : 'ts';
  const directory = resolve(root, `packages/${framework}/src/components`);
  const adapterSource = await readFile(
    resolve(root, `packages/${framework}/src/index.${extension}`),
    'utf8',
  );
  const typeSymbols = new Set(
    [
      ...adapterSource.matchAll(
        /export\s+(?:type|interface)\s+([A-Za-z0-9_$]+)/g,
      ),
    ].map((match) => match[1]),
  );
  await mkdir(directory, { recursive: true });
  for (const component of registry.components) {
    const symbols = registry.symbols[framework][component];
    if (!symbols?.length)
      throw new Error(`${framework}/${component} has no symbols`);
    const values = symbols.filter((symbol) => !typeSymbols.has(symbol));
    const types = symbols.filter((symbol) => typeSymbols.has(symbol));
    const path = resolve(directory, `${component}.${extension}`);
    const existing = await readFile(path, 'utf8').catch(() => '');
    if (existing && !existing.startsWith('// Generated by')) continue;
    const source = [
      '// Generated by scripts/generate-entrypoints.mjs.',
      values.length
        ? `export { ${values.join(', ')} } from '../index.js';`
        : '',
      types.length
        ? `export type { ${types.join(', ')} } from '../index.js';`
        : '',
      '',
    ]
      .filter((line, index, lines) => line || index === lines.length - 1)
      .join('\n');
    await writeFile(
      path,
      await format(source, { ...prettierOptions, parser: 'typescript' }),
    );
  }
}

const angularSymbols = [
  ...new Set(
    Object.values(registry.symbols.angular)
      .flat()
      .filter((symbol) => /(?:Component|Directive)$/.test(symbol)),
  ),
];
const angularAll = `// Generated by scripts/generate-entrypoints.mjs.\nimport { ${angularSymbols.join(', ')} } from './index.js';\nexport { ${angularSymbols.join(', ')} } from './index.js';\n\nexport const SIMURGH_COMPONENTS = [\n${angularSymbols.map((symbol) => `  ${symbol},`).join('\n')}\n] as const;\n`;
await writeFile(
  resolve(root, 'packages/angular/src/all.ts'),
  await format(angularAll, { ...prettierOptions, parser: 'typescript' }),
);
